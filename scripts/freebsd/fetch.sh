#!/usr/bin/env bash
# Fetch and check the tree of one pin of conf/freebsd/pins.conf, or of pins.toml, on the host.
#
#   fetch.sh PIN
#
# It prints the path of an archive of the tree and the number of leading path parts to strip from
# its member names (tar --strip-components). When RB_OUT is set, it writes "pin kind source hash" to
# RB_OUT/source.txt. Archives are kept in RB_CACHE. A cached txz is checked again before it is used.
#
# A txz pin is the release file itself, checked by SHA-256. Its members start with usr/src/.
# A pin that pins.conf does not list, such as freebsd-15.2, is read from pins.toml by pin-line.py:
# its src.txz when it is a release, or else its commit. So a release that rb sets wrote on the day
# it was tagged can be built that day (04.7).
# A git pin is fetched at depth 1 by its full commit hash and written with git archive, so the tree
# has no .git and nothing in it is generated by us. RB_COMMIT, a full commit hash, replaces the
# pinned commit of a git pin, to build another commit of the branch.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
pin=$1
: "${RB_CACHE:=$HOME/.cache/rb}"
mkdir -p "$RB_CACHE"

line="$(awk -v p="$pin" '$1 == p' "$here/../../conf/freebsd/pins.conf")"
if [ -z "$line" ]; then
	line="$(python3 -I "$here/pin-line.py" "$here/../../pins.toml" "$pin")" || {
		echo "no pin $pin in conf/freebsd/pins.conf or pins.toml" >&2
		exit 2
	}
fi
read -r _ kind source hash <<< "$line"
if [ -n "${RB_COMMIT:-}" ]; then
	if [ "$kind" != git ] || ! [[ $RB_COMMIT =~ ^[0-9a-f]{40}$ ]]; then
		echo "RB_COMMIT must be a full commit hash, for a git pin" >&2
		exit 2
	fi
	hash=$RB_COMMIT
fi
tar_out="$RB_CACHE/freebsd-src-$pin-${hash:0:12}.tar"
archive=""
strip=0

case $kind in
txz)
	txz="$RB_CACHE/freebsd-src-$pin-${hash:0:12}.txz"
	if [ ! -f "$txz" ] || ! echo "$hash  $txz" | sha256sum -c --status -; then
		curl -sfL --retry 3 --retry-all-errors -o "$txz.part" "$source"
		mv "$txz.part" "$txz"
	fi
	echo "$hash  $txz" | sha256sum -c - >&2
	archive="$txz"
	strip=2
	;;
git)
	if [ ! -f "$tar_out" ]; then
		repo="$RB_CACHE/git-$pin"
		rm -rf "$repo"
		git init -q "$repo"
		git -C "$repo" fetch -q --depth 1 "$source" "$hash"
		got="$(git -C "$repo" rev-parse FETCH_HEAD)"
		if [ "$got" != "$hash" ]; then
			echo "fetched $got, wanted $hash" >&2
			exit 1
		fi
		git -C "$repo" archive --format=tar -o "$tar_out.part" FETCH_HEAD
		rm -rf "$repo"
		mv "$tar_out.part" "$tar_out"
	fi
	archive="$tar_out"
	strip=0
	;;
*)
	echo "pin $pin has an unknown kind $kind" >&2
	exit 2
	;;
esac

if [ -n "${RB_OUT:-}" ]; then
	mkdir -p "$RB_OUT"
	printf '%s\t%s\t%s\t%s\n' "$pin" "$kind" "$source" "$hash" > "$RB_OUT/source.txt"
fi
echo "$archive $strip"
